def ensemble(N):
    """Each internal-signal detector OR windowed perplexity, each at 2.5% (budget split fixed in advance)."""
    from mtkaudit.matched import calibration_rows_v2
    res = {}
    for m in MODELS:
        items, dets = matched_scores(m)
        if items is None or "Windowed PPL" not in dets:
            continue
        rows = lambda p, f=None: [i["row"] for i in items if i["population"] == p and (f is None or i["family"] == f)]
        cal, ev = calibration_rows_v2(items), rows("benign_eval")
        fams = sorted({i["family"] for i in items if i["population"] == "release_attack"})
        ppl = dets["Windowed PPL"]
        tp = np.quantile(ppl[cal], 0.975)
        for d in INTERNAL:
            if d not in dets:
                continue
            s_ = dets[d]
            t = np.quantile(s_[cal], 0.975)
            flag = lambda r: (s_[r] > t) | (ppl[r] > tp)
            big = {f: float(flag(rows("release_attack", f)).mean()) for f in fams if len(rows("release_attack", f)) >= 50}
            worst = min(big, key=big.get)
            res[(m, d)] = {"fpr": float(flag(ev).mean()), "saa": big["saa"], "worst": worst, "worst_tpr": big[worst]}
    for m in MODELS:
        r = res.get((m, "MTK"))
        if r:
            M = MMAC[m]
            N[f"Ens{M}SAA"], N[f"Ens{M}FPR"] = f3(r["saa"]), f3(r["fpr"])
            N[f"Ens{M}Worst"], N[f"Ens{M}WorstTPR"] = FAM[r["worst"]], f3(r["worst_tpr"])
    if res:
        N["EnsN"] = str(len(res))
        N["EnsSAACaught"] = str(sum(v["saa"] >= 0.9 for v in res.values()))
        N["EnsFamilyMissed"] = str(sum(v["worst_tpr"] < 0.2 for v in res.values()))
        N["EnsFPRMin"], N["EnsFPRMax"] = f3(min(v["fpr"] for v in res.values())), f3(max(v["fpr"] for v in res.values()))


def gate(N):
    p = RP / "gate.json"
    if not p.exists():
        missing("gate")
        return
    g = json.loads(p.read_text())
    diffs = [v.get("max_abs_score_diff", v.get("worst_score_diff")) for v in g["models"].values()]
    ok = all(v.get("status") == "PASS" for v in g["models"].values())
    N["GatePass"] = "all four" if ok else missing("gate fail")
    worst = max(d for d in diffs if d is not None)
    nv = max(v.get("max_abs_score_diff", 0) for k, v in g["models"].items() if k != "vicuna")
    mant_nv, exp_nv = f"{nv:.0e}".split("e")
    N["GateMaxDiffNonVicuna"] = "0" if nv == 0 else rf"{mant_nv}\times10^{{{int(exp_nv)}}}"
    mant, exp = f"{worst:.0e}".split("e")
    N["GateMaxDiff"] = "0" if worst == 0 else rf"{mant}\times10^{{{int(exp)}}}"


