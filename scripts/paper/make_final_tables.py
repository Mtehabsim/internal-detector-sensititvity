def rule_x(N):
    """The AUROC > 1 - alpha rule across detectors (rule_crossdetector.py)."""
    p = RES / "rule_test" / "cross_detector.json"
    if not p.exists():
        missing("rule test")
        return
    r = json.loads(p.read_text())
    N["RuleXN"] = f"{r['n_cells']:,}".replace(",", "{,}")
    N["RuleXAll"] = f"{100 * r['overall']['agreement']:.1f}"
    N["RuleXConc"] = f"{100 * r['by_concentration']['lt_0.5']['agreement']:.1f}"
    N["RuleXSpread"] = f"{100 * r['by_concentration']['ge_1']['agreement']:.1f}"
    N["RuleXMTK"] = f"{100 * r['by_detector']['MTK']['agreement']:.1f}"
    pos = float(np.mean([c["tpr"] > 0.5 for c in r["cells"]]))
    N["RuleXBaseline"] = f"{100 * max(pos, 1 - pos):.1f}"      # always predicting the more common outcome


