MISSING = []


def missing(what):
    MISSING.append(what)
    return r"\missing{}"


class Numbers:
    def __init__(self):
        self.items = {}

    def __setitem__(self, name, value):
        assert name.isalpha(), name
        self.items[name] = value

    def tex(self):
        lines = ["% generated by make_final_tables.py -- do not edit",
                 r"\providecommand{\missing}{\textbf{??}}"]
        for k, v in sorted(self.items.items()):
            lines.append(rf"\newcommand{{\n{k}}}{{{v}}}")
        return "\n".join(lines) + "\n"


