         r"0--49, so those models have 50 draws; the others have 51.}",
         r"\label{tab:r2}", r"\footnotesize", r"\setlength{\tabcolsep}{3.5pt}",
         r"\begin{tabular}{lrllllrrr}", r"\toprule",
