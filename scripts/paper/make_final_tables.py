            if variant == "as_shipped" and len(_MED) == 4:
                N["LotteryMedMin"], N["LotteryMedMax"] = f3(min(_MED.values())), f3(max(_MED.values()))
            N[f"{M}LotterySAATPRmin"] = f3(min(saa))
            N[f"{M}LotterySAATPRmax"] = f3(max(saa))
            N[f"{M}LotterySAATPRmed"] = f3(float(np.median(saa)))
            N[f"{M}WorstFamMax"] = f3(max(w))
