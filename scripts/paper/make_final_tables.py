def review3(N):
    """Numbers added for the third outside review (2026-09-29): exact exceedance test for the Dolly thresholds,
    goal overlap with MTK's anchors, an equal-variance Gaussian reading of one AUROC, bank-only family spans, and the
    targeted interventions against their control arm."""
    from scipy.stats import betabinom, norm
    # (1) exact exceedance test, one-sided at 5% (a 95% predictive bound under exchangeability). np.quantile's
    # interpolated 95% threshold lies between the (k+1)-th and k-th highest of the n calibration scores,
    # k = floor(0.05 (n-1)) + 1. The count of m evaluation prompts above the j-th highest calibration score is
    # Beta-Binomial(m, j, n-j+1), and the count above the threshold is at most the count above the (k+1)-th highest,
    # so the conservative exact test uses j = k+1. Holm's step-down procedure is applied across the 40
    # detector x model x dataset tests.
    sm = json.loads((RES / "dolly_calibration" / "summary_v2.json").read_text())
    wc = json.loads((RES / "wildchat" / "summary.json").read_text())
    dets = ("MTK", "Probe", "GradSafe", "HiddenDetect", "Windowed PPL")

    def order_stat(n):
        j = int(np.floor(0.05 * (n - 1))) + 2
        return j, n - j + 1

    def holm(pv, a=0.05):
        keys = sorted(pv, key=pv.get)
        rej = {q: False for q in pv}
        for r, q in enumerate(keys):
            if pv[q] > a / (len(keys) - r):
                break
            rej[q] = True
        return rej

    pv = {}
    for m in MODELS:
        a, b = order_stat(sm[m]["_split"]["n_calibration"])
        for d in dets:
            for ds, fpr in (("TC", sm[m][d]["dolly"]["fpr_toxicchat_eval"]), ("WC", wc[m][d]["dolly"]["fpr_wildchat_eval"])):
                x = int(round(fpr * 500))
                assert abs(x / 500 - fpr) < 1e-9
                pv[(m, d, ds)] = float(betabinom.sf(x - 1, 500, a, b))
    sig, sig_h = {q: v < 0.05 for q, v in pv.items()}, holm(pv)
    for suf, sg in (("", sig), ("Holm", sig_h)):
        N[f"ExcEveryBoth{suf}"] = str(sum(all(sg[(m, d, ds)] for m in MODELS for ds in ("TC", "WC")) for d in dets))
        N[f"ExcGSPairs{suf}"] = str(sum(sg[(m, "GradSafe", ds)] for m in MODELS for ds in ("TC", "WC")))
        N[f"ExcHDPairs{suf}"] = str(sum(sg[(m, "HiddenDetect", ds)] for m in MODELS for ds in ("TC", "WC")))
        N[f"ExcTCPairs{suf}"] = str(sum(sg[(m, d, "TC")] for m in MODELS for d in dets))
        N[f"ExcWCPairs{suf}"] = str(sum(sg[(m, d, "WC")] for m in MODELS for d in dets))
    ns = sorted({sm[m]["_split"]["n_calibration"] for m in MODELS})
    js = {order_stat(n)[0] for n in ns}
    assert len(js) == 1
    j0 = js.pop()
    N["ExcOrderStat"], N["ExcOrderStatUpper"] = str(j0), str(j0 - 1)   # the threshold lies between the two
    # expected null exceedance j / (n + 1) and the one-sided 95% bound for 500 evaluation prompts (199-200 calibration)
    nul = [100 * order_stat(n)[0] / (n + 1) for n in ns]
    N["ExcNullPctMin"], N["ExcNullPctMax"] = f"{min(nul):.2f}", f"{max(nul):.2f}"
    his = [float(betabinom.ppf(0.95, 500, *order_stat(n))) / 500 for n in ns]
    N["ExcChanceHiMin"], N["ExcChanceHiMax"] = f3(min(his)), f3(max(his))
    N["ExcCalMin"], N["ExcCalMax"] = str(min(ns)), str(max(ns))
    # the same conservative test on ToxicChat's human-labeled non-toxic prompts (m = 217-241 per model)
    tl = json.loads((RES / "uncertainty" / "toxicchat_labels.json").read_text())["models"]
    pvh = {}
    for m in MODELS:
        h = tl[m]["counts"]["benign_eval"]["human"]
        a, b = order_stat(sm[m]["_split"]["n_calibration"])
        for d in dets:
            f = tl[m]["dolly_threshold_fpr"][d]["human"]
            x = int(round(f * h))
            assert abs(x / h - f) < 1e-9
            pvh[(m, d)] = float(betabinom.sf(x - 1, h, a, b))
    for suf, sg in (("", {q: v < 0.05 for q, v in pvh.items()}), ("Holm", holm(pvh))):
        N[f"TCLabSigEveryModel{suf}"] = str(sum(all(sg[(m, d)] for m in MODELS) for d in dets))
        N[f"TCLabHDSig{suf}"] = str(sum(sg[(m, "HiddenDetect")] for m in MODELS))
    # WildChat jailbreak-marker control, pair by pair: change in FPR, and pairs still beyond the bound (m = 490)
    ch, kept = [], 0
    for m in MODELS:
        a, b = order_stat(sm[m]["_split"]["n_calibration"])
        for d in dets:
            v = wc[m][d]["dolly"]
            mk = 500 - wc["wildchat_eval_marker_excluded"]
            x = int(round(v["fpr_wildchat_no_markers_eval"] * mk))
            assert abs(x / mk - v["fpr_wildchat_no_markers_eval"]) < 1e-9
            ch.append(abs(v["fpr_wildchat_no_markers_eval"] - v["fpr_wildchat_eval"]))
            kept += sig[(m, d, "WC")] and float(betabinom.sf(x - 1, mk, a, b)) < 0.05
    N["WCMarkerMaxChange"] = f3(max(ch))
    N["WCMarkerSigKept"] = str(kept)
    # (2) goal overlap (goal_overlap.py)
    go = json.loads((RES / "uncertainty" / "goal_overlap.json").read_text())["models"]
    with_goal = {f for m in MODELS for f, v in go[m].items() if v.get("goal_field") and f != "SAA-850"}
    N["GOFamsGoal"] = str(len({f.replace("nonagcg", "nanogcg") for f in with_goal}))
    N["GOFamsOverlap"] = str(len({f.replace("nonagcg", "nanogcg") for m in MODELS for f, v in go[m].items()
                                  if v.get("goal_field") and f != "SAA-850" and v["n_overlap"] > 0}))
